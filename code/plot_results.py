from __future__ import annotations

from pathlib import Path
from typing import Dict, List
import csv

import numpy as np
import matplotlib.pyplot as plt


# Part 10: Plotting
def load_summary_as_numeric(config) -> List[Dict[str, object]]:
    """Load summary CSV and convert numeric fields.
    Load the summary CSV and convert numeric fields.
    """
    summary_path = Path(config.output_dir) / config.summary_file
    with summary_path.open(mode="r", newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    numeric_fields = [
        "accuracy_mean",
        "accuracy_std",
        "training_time_mean",
        "training_time_std",
        "inference_time_mean",
        "inference_time_std",
    ]

    for row in rows:
        for field in numeric_fields:
            row[field] = float(row[field])
        row["n_runs"] = int(row["n_runs"])

    return rows


def plot_grouped_bar(
    rows: List[Dict[str, object]],
    config,
    dataset_info: Dict[str, Dict[str, int | str]],
    model_display_names: Dict[str, str],
    metric_mean: str,
    metric_std: str,
    ylabel: str,
    title: str,
    output_filename: str,
) -> None:
    """Create grouped bar chart with error bars.
    Create a grouped bar chart with error bars.
    """
    output_dir = Path(config.output_dir)
    figures_dir = output_dir / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    datasets_order = list(config.datasets)
    models_order = list(config.models)

    lookup = {(str(r["dataset"]), str(r["model"])): r for r in rows}

    x = np.arange(len(datasets_order))
    width = 0.18

    plt.figure(figsize=(10, 6))

    for idx, model_name in enumerate(models_order):
        means = []
        stds = []
        for dataset_name in datasets_order:
            row = lookup[(dataset_name, model_name)]
            means.append(float(row[metric_mean]))
            stds.append(float(row[metric_std]))

        offset = (idx - (len(models_order) - 1) / 2) * width
        plt.bar(
            x + offset,
            means,
            width,
            yerr=stds,
            capsize=3,
            label=model_display_names[model_name],
        )

    plt.xticks(x, [str(dataset_info[d]["display_name"]) for d in datasets_order])
    plt.ylabel(ylabel)
    plt.title(title)
    plt.legend()
    plt.tight_layout()

    output_path = figures_dir / output_filename
    plt.savefig(output_path, dpi=300)
    plt.close()

    print(f"Figure saved to: {output_path}")


def plot_tradeoff(rows: List[Dict[str, object]], config, dataset_info: Dict[str, Dict[str, int | str]], model_display_names: Dict[str, str]) -> None:
    """Plot accuracy vs training time trade-off.
    Plot the trade-off between accuracy and training time.
    """
    output_dir = Path(config.output_dir)
    figures_dir = output_dir / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    datasets_order = list(config.datasets)
    models_order = list(config.models)
    lookup = {(str(r["dataset"]), str(r["model"])): r for r in rows}

    # Single figure with 2x2 panels. This is acceptable here because it is one
    # saved project figure, not a user-facing chart generated by the Python tool.
    # This creates one 2x2 panel figure for the project files.
    fig, axes = plt.subplots(2, 2, figsize=(11, 8))
    axes = axes.flatten()

    for ax, dataset_name in zip(axes, datasets_order):
        for model_name in models_order:
            row = lookup[(dataset_name, model_name)]
            train_time = float(row["training_time_mean"])
            accuracy = float(row["accuracy_mean"])
            ax.scatter(train_time, accuracy)
            ax.annotate(
                model_display_names[model_name],
                (train_time, accuracy),
                fontsize=8,
                xytext=(4, 4),
                textcoords="offset points",
            )

        ax.set_title(str(dataset_info[dataset_name]["display_name"]))
        ax.set_xlabel("Training time (s)")
        ax.set_ylabel("Validation accuracy")
        ax.grid(True, alpha=0.3)

    plt.tight_layout()
    output_path = figures_dir / "accuracy_training_tradeoff.png"
    plt.savefig(output_path, dpi=300)
    plt.close()

    print(f"Figure saved to: {output_path}")


def make_all_plots(config, dataset_info: Dict[str, Dict[str, int | str]], model_display_names: Dict[str, str]) -> None:
    """Generate all result figures.
    Generate all result figures.
    """
    rows = load_summary_as_numeric(config)

    plot_grouped_bar(
        rows=rows,
        config=config,
        dataset_info=dataset_info,
        model_display_names=model_display_names,
        metric_mean="accuracy_mean",
        metric_std="accuracy_std",
        ylabel="Validation accuracy",
        title="Validation Accuracy Across Datasets",
        output_filename="accuracy_comparison.png",
    )

    plot_grouped_bar(
        rows=rows,
        config=config,
        dataset_info=dataset_info,
        model_display_names=model_display_names,
        metric_mean="training_time_mean",
        metric_std="training_time_std",
        ylabel="Training time (s)",
        title="Training Time Across Datasets",
        output_filename="training_time_comparison.png",
    )

    plot_grouped_bar(
        rows=rows,
        config=config,
        dataset_info=dataset_info,
        model_display_names=model_display_names,
        metric_mean="inference_time_mean",
        metric_std="inference_time_std",
        ylabel="Inference time (s)",
        title="Inference Time Across Datasets",
        output_filename="inference_time_comparison.png",
    )

    plot_tradeoff(rows, config, dataset_info, model_display_names)

